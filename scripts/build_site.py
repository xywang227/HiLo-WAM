"""Package only referenced website files; never copy Git history or source documents."""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit
import shutil

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'dist'


class Assets(HTMLParser):
    def __init__(self):
        super().__init__()
        self.references = set()
        self.external = set()

    def handle_starttag(self, tag, attrs):
        for key, value in attrs:
            if key not in {'src', 'href', 'poster'} or not value:
                continue
            url = urlsplit(value)
            if url.scheme or url.netloc:
                self.external.add(value)
            elif url.path:
                self.references.add(unquote(url.path))


def build():
    html = (ROOT / 'index.html').read_text(encoding='utf-8')
    assets = Assets()
    assets.feed(html)
    anonymous = 'Anonymous authors' in html
    if anonymous and assets.external:
        raise ValueError('Anonymous builds must not contain external links or remote assets.')
    files = {'index.html', '.nojekyll'} | assets.references
    for relative in files:
        path = ROOT / relative
        if not path.resolve().is_relative_to(ROOT) or not path.is_file():
            raise ValueError(f'Missing or out-of-project asset: {relative}')
        if path.suffix.lower() in {'.pdf', '.docx', '.tex'} or path.name.startswith('.DS_Store'):
            raise ValueError(f'Source document or system file is not publishable: {relative}')
    # Remove stale output only; this directory is generated by this script.
    if OUTPUT.exists():
        if OUTPUT.is_symlink():
            raise ValueError('The output directory must not be a symlink.')
        if not (OUTPUT / '.site-build').is_file():
            raise ValueError('Refusing to replace a directory not created by this builder.')
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    for relative in sorted(files):
        destination = OUTPUT / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / relative, destination)
    (OUTPUT / '.site-build').write_text('Generated website assets only.\n')
    print(f'Built {len(files)} files in dist/ ({"anonymous" if anonymous else "release"}).')


if __name__ == '__main__':
    build()
